// Combines the base schema and every migration, in order, into one script for a
// brand-new, empty Supabase project: supabase/setup/full_setup.sql.
// Run after adding a migration: node scripts/build-supabase-setup.mjs
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const files = [
  'sql_schema.sql',
  'migrate_add_pickup_location.sql',
  'add_missing_columns.sql',
  'migrate_setup_storage_buckets.sql',
  ...readdirSync(join(root, 'supabase/migrations')).filter(name => name.endsWith('.sql')).sort().map(name => `supabase/migrations/${name}`),
];

const header = `-- DHL Express: complete database setup for a NEW, EMPTY Supabase project.
-- Generated by scripts/build-supabase-setup.mjs. Do not edit; edit the source files and regenerate.
--
-- Supabase → SQL Editor → New query → paste this whole file → Run.
-- It runs as a single transaction: if any statement fails, nothing is applied.
-- Do not run it on a project that already has these tables; apply new migrations instead.
--
-- Contents, in order:
${files.map(file => `--   ${file}`).join('\n')}
`;

const body = files.map(file => `\n-- ===========================================================================\n-- ${file}\n-- ===========================================================================\n\n${readFileSync(join(root, file), 'utf8').replace(/^﻿/, '').trimEnd()}\n`).join('');
const target = join(root, 'supabase/setup/full_setup.sql');
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, `${header}${body}`);
console.log(`Wrote ${target} (${files.length} files)`);
